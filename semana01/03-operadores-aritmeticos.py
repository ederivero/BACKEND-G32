a = 10
b = 50

# Suma
resultado = a + b
print(resultado)

# Resta
resultado = a - b
print(resultado)

# Multiplicacion
resultado = a * b
print(resultado)

# Division
resultado = a / b
print(resultado)

# Division Exacta (descarta decimales)
resultado = a // b
print(resultado)

# Modulo (Resto de la division)
resultado = a % b
print(resultado)

# Potencia
resultado = a ** b
print(resultado)

# Para los string 
palabra1 = 'ala'
palabra2 = 'ole'

# Suma > Concatenacion
resultado = palabra1 + palabra2
print(resultado)

# Multiplicacion (Si multiplico mi string por un entero se repetira la cantidad de veces)
resultado = palabra1 * 2
print(resultado)

